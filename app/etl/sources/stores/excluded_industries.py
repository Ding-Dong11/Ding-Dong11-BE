def is_excluded(industry_code: str | None) -> bool:
    """industry_code 가 제외 목록에 해당하면 True."""
    if not industry_code:
        return False
    if any(industry_code.startswith(p) for p in EXCLUDED_PREFIXES):
        return True
    return industry_code in EXCLUDED_CODES
